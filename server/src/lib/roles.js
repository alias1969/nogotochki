/**
 * Роли: словарь и правила проверки.
 *
 * Роли человека — список, а не одно значение (раздел 4.21 схемы).
 * У владелицы студии есть и кабинет мастера, и админ-панель; с единственным
 * полем role ей пришлось бы заводить второй аккаунт и разорвать свою
 * историю визитов.
 *
 * Отсюда главное правило: право проверяется вопросом «есть ли роль
 * в списке», а не «совпадает ли роль». Равенство role === 'master'
 * закрыло бы кабинет мастера перед той самой владелицей, у которой
 * рядом стоит роль администратора.
 *
 * Роли берутся только из базы (таблица user_roles), в запросе их никто
 * не передаёт: роль из тела запроса — это не проверка прав, а вежливая
 * просьба к злоумышленнику назвать себя честно.
 */
export const ROLES = ['user', 'master', 'admin'];

/**
 * Роли от сильной к слабой.
 *
 * Порядок нужен там, где действие выполняется в одной роли, а их у человека
 * несколько: кто создаёт запись, чьё правило переноса применять, как
 * назвать действующего в журнале.
 */
export const BY_STRENGTH = ['admin', 'master', 'user'];

/** Есть ли роль в списке. Основная проверка прав во всём сервисе. */
export function has(user, role) {
  return Boolean(user) && Array.isArray(user.roles) && user.roles.includes(role);
}

/** Есть ли хотя бы одна из перечисленных ролей. */
export function hasAny(user, roles) {
  return roles.some((role) => has(user, role));
}

/** Самая сильная роль человека — для журнала, витрин и сообщений об отказе. */
export function strongest(user) {
  return BY_STRENGTH.find((role) => has(user, role)) ?? null;
}

/** Список в том же виде, в каком он лежит в снимке сессии: по алфавиту, через запятую. */
export function serialize(roles) {
  return [...new Set(roles)].sort().join(',');
}

/** Разбор снимка ролей из сессии. */
export function deserialize(text) {
  return typeof text === 'string' && text !== '' ? text.split(',') : [];
}

/**
 * Политика действия для человека с несколькими ролями.
 *
 * Правило: **человек действует в самой сильной из своих ролей, которой
 * это действие разрешено.** Администратор-мастер создаёт запись как
 * администратор, потому что администратору это разрешено, а мастеру нет.
 * Мастер-клиент записывается сам как клиент: мастеру запись создавать
 * нельзя, и роль клиента оказывается единственной подходящей.
 *
 * Простое «взять политику сильнейшей роли» здесь не годится — оно
 * отняло бы у мастера-клиента возможность записаться к коллеге.
 *
 * Возвращает { role, policy } или null, если ни одна роль не подходит.
 * Если политики есть, но ни одна не разрешает действие, возвращается
 * самая сильная из них — чтобы отказ объяснялся её словами, а не молчал.
 */
export function pickPolicy(user, table, permits = () => true) {
  let fallback = null;
  for (const role of BY_STRENGTH) {
    if (!has(user, role)) continue;
    const policy = table[role];
    if (policy === undefined) continue;
    if (permits(policy)) return { role, policy, allowed: true };
    if (fallback === null) fallback = { role, policy, allowed: false };
  }
  return fallback;
}
