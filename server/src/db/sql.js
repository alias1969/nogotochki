/**
 * Сборка тех кусков SQL, которые нельзя передать параметром.
 *
 * Значение в запросе всегда параметр — `?` или `:имя`. Это правило
 * без исключений: подстановка значения в текст запроса и есть SQL-инъекция,
 * а не «почти безопасный приём, если данные проверены».
 *
 * Но именами колонок и числом мест в `IN (...)` параметры не бывают:
 * SQLite готовит запрос до того, как узнаёт значения, и `SET ? = ?`
 * он выполнить не может. Эти два куска приходится собирать строкой —
 * и ровно поэтому они собираются здесь, в одном месте, под проверкой.
 *
 * Проверка простая: имя колонки обязано быть в списке разрешённых для
 * этой таблицы. Список задан в коде и от запроса не зависит никак.
 * Пока правка идёт через эти функции, поле, которого нет в списке,
 * не попадёт в запрос, даже если однажды кто-то напишет `patch = {...body}`
 * вместо разбора по одному полю.
 *
 * Несовпадение — ошибка программиста, а не пользователя: наружу уходит
 * 500 без подробностей, в журнал сервера — имя поля.
 */

/** Допустимое имя колонки. Вторая линия на случай пустого или кривого списка. */
const COLUMN_RE = /^[a-z][a-z0-9_]*$/;

/**
 * `SET name = :name, phone = :phone` — только из разрешённых колонок.
 *
 * Возвращает и текст, и сам набор значений: вызывающему не приходится
 * собирать параметры отдельно и случайно разойтись с текстом.
 */
export function setClause(patch, allowed) {
  const fields = Object.keys(patch);

  for (const field of fields) {
    if (!allowed.includes(field) || !COLUMN_RE.test(field)) {
      throw new Error(
        `Поле ${JSON.stringify(field)} не разрешено к правке. ` +
          `Разрешены: ${allowed.join(', ')}`,
      );
    }
  }

  return {
    fields,
    clause: fields.map((field) => `${field} = :${field}`).join(', '),
    params: Object.fromEntries(fields.map((field) => [field, patch[field]])),
  };
}

/**
 * `?, ?, ?` под список значений известной длины.
 *
 * Сами значения идут параметрами; строкой собирается только число мест.
 */
export function placeholders(count) {
  if (!Number.isInteger(count) || count < 1) {
    throw new Error(`Число мест в IN(...) должно быть положительным целым, получено: ${count}`);
  }
  return new Array(count).fill('?').join(', ');
}
