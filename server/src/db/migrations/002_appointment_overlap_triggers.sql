-- =====================================================================
-- 002_appointment_overlap_triggers.sql — запрет пересечения записей
-- =====================================================================
--
-- Источник: Docs/db-schema.md, версия 1.6, раздел 6.3.
--
-- Зачем.
--   Уникальный индекс ux_appointments_master_slot из миграции 001 ловит
--   только совпадение минуты начала: (master_id, starts_at, active_slot).
--   Записи 10:00–11:30 и 10:30–11:00 у одного мастера он пропускает —
--   начало разное, а визиты накладываются. В SQLite нет типа-интервала
--   и ограничения исключения (EXCLUDE USING gist, как в PostgreSQL),
--   поэтому пересечение приходится проверять триггером.
--
-- Почему триггеры, а не только проверка в коде API.
--   Проверка в коде защищает ровно до тех пор, пока все пути записи идут
--   через неё. Ручная правка в консоли, скрипт переноса данных, будущий
--   кабинет мастера — каждый новый путь обходит её молча. Запрет,
--   выраженный в базе, действует для всех путей сразу.
--
-- Условие пересечения — строгие неравенства в обе стороны:
--     начало нового < конец существующего  И  конец нового > начало существующего
--   Строгие намеренно: визиты вплотную (15:00–16:00 и 16:00–17:00)
--   пересечением не считаются, иначе мастер не смог бы принимать подряд.
--
-- В проверке участвуют только записи со статусом 'booked' — так же,
-- как в частичном уникальном индексе и в расчёте свободного времени.
-- Отменённая запись слот не блокирует: время сразу доступно другим.
--
-- Текст ошибки 'appointment_overlap' — часть интерфейса базы: API ловит
-- именно его и превращает в ответ 409 со списком свободных слотов.
-- Менять эту строку нельзя, не поправив src/services/appointments.js.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Новая запись поверх чужого визита
-- ---------------------------------------------------------------------
CREATE TRIGGER trg_appointments_no_overlap_insert
BEFORE INSERT ON appointments
WHEN NEW.status = 'booked'
BEGIN
    SELECT RAISE(ABORT, 'appointment_overlap')
     WHERE EXISTS (
        SELECT 1
          FROM appointments a
         WHERE a.master_id = NEW.master_id
           AND a.status    = 'booked'
           AND a.starts_at < NEW.ends_at
           AND a.ends_at   > NEW.starts_at
     );
END;


-- ---------------------------------------------------------------------
-- Перенос, смена мастера и возврат отменённой записи в работу
-- ---------------------------------------------------------------------
-- Второй триггер нужен потому, что запись меняется двумя разными
-- способами, и UPDATE — не менее опасный из них:
--   * перенос меняет starts_at и ends_at той же строки;
--   * администратор может сменить мастера у существующей записи;
--   * отменённую запись можно вернуть в 'booked', а её время
--     за время отмены уже могли занять.
--
-- Из проверки исключается сама изменяемая строка: без этого запись
-- пересекалась бы сама с собой при любой правке — например, при смене
-- статуса на 'completed' или при добавлении заметки администратора.
-- Исключаются оба идентификатора, OLD и NEW: они совпадают всегда,
-- кроме экзотического случая правки самого первичного ключа.
CREATE TRIGGER trg_appointments_no_overlap_update
BEFORE UPDATE ON appointments
WHEN NEW.status = 'booked'
BEGIN
    SELECT RAISE(ABORT, 'appointment_overlap')
     WHERE EXISTS (
        SELECT 1
          FROM appointments a
         WHERE a.id       <> OLD.id
           AND a.id       <> NEW.id
           AND a.master_id = NEW.master_id
           AND a.status    = 'booked'
           AND a.starts_at < NEW.ends_at
           AND a.ends_at   > NEW.starts_at
     );
END;
