-- =====================================================================
-- 005_service_category_name.sql — уникальное имя категории услуг
-- =====================================================================
--
-- Источник: Docs/db-schema.md, версия 1.9, ограничение 4а.
--
-- Зачем.
--   Уникальность услуги проверяется парой (category_id, name) — это
--   ограничение 4 из первой миграции. Но саму категорию до сих пор
--   ничто не мешало завести дважды: две «Уход», и услуги расползаются
--   по ним незаметно. На витрине два одинаковых раздела, в каждом
--   половина услуг, а администратор не понимает, почему «пропал» маникюр.
--
--   Ограничение 4 здесь не спасает: оно сравнивает пару с category_id,
--   а категории-близнецы имеют разные идентификаторы, и с его точки
--   зрения конфликта нет.
--
-- Индекс обычный, а не по выражению ulower(name).
--   Регистронезависимую проверку («Уход» и «уход») делает код API:
--   встроенный lower() в SQLite не знает кириллицы, а индекс по своей
--   функции сломал бы любую запись из сторонних инструментов —
--   sqlite3 в консоли о функции ulower не знает и откажется вставлять
--   строку вообще. Цена такого индекса выше пользы: в базе остаётся
--   простое ограничение, а вежливую проверку делает код.
-- =====================================================================

CREATE UNIQUE INDEX ux_service_category_name ON service_categories(name);
