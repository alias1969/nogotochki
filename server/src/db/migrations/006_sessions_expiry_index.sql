-- =====================================================================
-- 006_sessions_expiry_index.sql — индекс для уборки истёкших сессий
-- =====================================================================
--
-- Источник: Docs/db-schema.md, версия 2.0, индекс 34, раздел 7.13.
--
-- Зачем.
--   Истёкшая сессия перестаёт пускать сама по себе: проверка берёт
--   только строки с expires_at > now. Но строка никуда не девается,
--   а в ней лежат хеш токена и строка браузера. Таблица от входа
--   к входу только росла: у активного клиента это новая строка
--   на каждое устройство и каждый повторный вход, и через год
--   живых среди них единицы.
--
--   Теперь мёртвые сессии удаляются при открытии новой — там, где
--   таблица и так пишется. Этому запросу нужен индекс по expires_at.
--
-- Почему не хватает ix_sessions_user.
--   В нём (user_id, expires_at), и user_id стоит первым. Уборка идёт
--   по всем пользователям сразу, без условия на user_id, — такой
--   запрос индексом не обслуживается и читает таблицу целиком.
--   Ровно так же для резервов заведён ix_holds_expires.
--
-- Данные не меняются: индекс ничего не удаляет и не переписывает,
-- удаляет код (services/auth.js, sweepExpiredSessions).
-- =====================================================================

CREATE INDEX IF NOT EXISTS ix_sessions_expires ON sessions(expires_at);
