-- =====================================================================
--
-- Источник: Docs/db-schema.md, раздел 4.19, и раздел «Роли и права
-- доступа» паспорта продукта.
--
-- Что это такое и чем не является.
--   Таблица role_permissions ничем не управляет. Права проверяются
--   в коде при каждом запросе; эта таблица — описание того, как они
--   устроены, чтобы администратор мог посмотреть на экране A10, кто
--   что может, не читая исходники. Решение 7.15 схемы.
--
--   Отсюда следует правило, которое легко нарушить: если поведение кода
--   меняется, строку здесь надо поправить отдельной миграцией. Матрица,
--   разошедшаяся с кодом, хуже отсутствующей — она врёт уверенно.
--
-- Это справочные данные, а не тестовые: они нужны и в проде, поэтому
-- лежат в миграции, а не в наполнении npm run seed.
-- =====================================================================

