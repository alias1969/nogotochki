/**
 * Доставка ссылки восстановления пароля наружу.
 *
 * Здесь проходит граница MVP, и это стоит проговорить прямо.
 *
 * Паспорт ограничивает сервис так: «Уведомления приходят только внутри
 * личного кабинета; интеграция с e-mail или Telegram не входит в MVP».
 * Восстановление пароля — единственное место, где это ограничение
 * упирается само в себя: человек, забывший пароль, в кабинет как раз
 * и не может войти, поэтому сообщить ему ссылку внутри кабинета
 * невозможно по определению.
 *
 * Выход выбран такой: весь механизм восстановления сделан полностью
 * и по-настоящему — одноразовый токен, хеш в базе, срок жизни, сброс
 * сессий. Не сделан один последний шаг: отправка письма. Вместо неё
 * ссылка пишется в журнал сервера, а в разработке ещё и возвращается
 * в ответе, чтобы поток можно было пройти целиком.
 *
 * Чтобы включить почту, достаточно заменить тело одной функции ниже.
 * Всё остальное — выдача токена, проверка, сброс — менять не придётся.
 *
 * ВАЖНО: в проде ссылка не возвращается в ответе никогда. Иначе любой,
 * кто знает чужой e-mail, получал бы ссылку для входа в чужой аккаунт
 * прямо в ответ на запрос.
 */
import { env } from '../config/env.js';

/** Ссылка, по которой человек попадёт на экран смены пароля. */
export function buildResetLink(token) {
  return `${env.appUrl.replace(/\/+$/, '')}/reset-password?token=${encodeURIComponent(token)}`;
}

/**
 * Отправить ссылку.
 *
 * Возвращает признак того, доставлена ли она по-настоящему. Пока
 * доставки нет, обработчик по этому признаку решает, показывать ли
 * ссылку в ответе.
 */
export function deliverResetLink({ email, link }) {
  if (env.isProduction) {
    // Сюда встанет отправка письма. Пока в проде ссылка не уходит никуда
    // и об этом честно пишется в журнал — молчаливая заглушка в проде
    // хуже, чем громкая.
    console.warn(
      `[восстановление пароля] Отправка письма не настроена. ` +
        `Ссылка для ${email} не доставлена.`,
    );
    return { delivered: false };
  }

  console.log(`[восстановление пароля] ${email}: ${link}`);
  return { delivered: false };
}

/** Показывать ли ссылку в ответе API. Только вне прода и только пока нет почты. */
export function mayExposeLink() {
  return !env.isProduction;
}
